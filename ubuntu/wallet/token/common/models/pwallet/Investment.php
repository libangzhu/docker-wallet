namespace common\models\pwallet;

use Yii;
use common\core\BaseActiveRecord;

/**
 * Class InvestmentType
 * @property integer $id
 * @property integer $uid
 * @property integer $tid
 * @property double $count
 * @property string $coin
 * @property string $address
 * @property string $create_at
 * @property string $update_at
 * @package common\models\pwallet
 */
class Investment extends BaseActiveRecord
{
    /**
     * @return null|object|\yii\db\Connection
     * @throws \yii\base\InvalidConfigException
     */
    public static function getDb()
    {
        return Yii::$app->get('db_pwallet');
    }

    public function formName()
    {
        return '';
    }

    public function rules()
    {
        return [
            [['id', 'uid', 'tid'], 'integer'],
            [['coin', 'address'], 'string'],
            [['count'], 'default']
        ];
    }

    /**
     * @param bool $runValidation
     * @param null $attributeNames
     * @return bool
     * @throws \Exception
     */
    public function save($runValidation = true, $attributeNames = null)
    {
        $uid = $this->uid;
        if (!Member::userExists($uid)) {
            throw new \Exception('用户不存在', '2300');
        }
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }

    public function attributeLabels()
    {
        return [
            'id'        => 'ID',
            'uid'       => 'UID',
            'tid'       => '类型',
            'count'     => '数量',
            'coin'      => '币种',
            'address'   => '地址',
            'status'    => '状态',
            'create_at' => '创建时间',
            'update_at' => '更新时间',
        ];
    }

    public static function getList($page = 1, $limit = 10, $condition = [])
    {
        $query = self::find()->from('investment as a')->select([
            'a.id',
            'a.uid',
            'c.nickname',
            'c.phone',
            'a.coin',
            'a.count',
            'b.name as type',
            'a.status',
            'a.address',
            'a.create_at',
            'a.update_at',
        ])->leftJoin('investment_type as b', 'a.tid=b.id')->leftJoin('member as c',
            'a.uid=c.uid')->orderBy('a.create_at');
        foreach ($condition as $item) {
            $query = $query->andWhere($item);
        }
        $count = $query->count();
        $data  = $query->offset(($page - 1) * 10)->limit($limit)->asArray()->all();
//        $sql   = $query->createCommand()->getSql();
        $data = ['count' => $count, 'data' => $data];
        if ($count > 0) {
            $data['code'] = 0;
        } else {
            $data['code'] = 1;
            $data['msg']  = '数据为空';
        }
        return $data;
    }

    public static function loadArray(array $data)
    {
        return self::getDb()->createCommand()->batchInsert(self::tableName(),
            ['uid', 'count', 'coin', 'tid', 'create_at'],
            $data)->execute();
    }
}